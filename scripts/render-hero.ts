import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { createTree } from "../src/tree/index.ts";
import type { Pen } from "../src/tree/pen.ts";
import { PICKER_SEED, TREE_IMAGE_PADDING, TREE_SIZE, type StagePlace } from "../src/scene/stages.ts";

type CanvasApi = typeof import("../../thrivling-worktrees/launch/node_modules/@napi-rs/canvas/index.js");
const { createCanvas } = createRequire(import.meta.url)(
  "D:\\code\\thrivling-worktrees\\launch\\node_modules\\@napi-rs\\canvas",
) as CanvasApi;
const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "public", "assets", "hero");
const MODULE = join(ROOT, "src", "scene", "heroStages.ts");
const MIN_AGE = 3;
const MAX_AGE = 90;
const STAGE_COUNT = 120;
const HEALTH = 100;
const IMAGE_PX = 768;
const FINAL_PX = 1536;
const LAYERS = ["seed", "shadow", "backMass", "wood", "trunkDetail", "soil", "frontMass", "leaves", "details", "blossoms"] as const;

function paintedBounds(pixels: Uint8ClampedArray, size: number) {
  let x0 = size, y0 = size, x1 = -1, y1 = -1;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      if (pixels[(y * size + x) * 4 + 3] === 0) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  if (x1 < 0) return { x: 0, y: 0, w: 1, h: 1 };
  const x = Math.max(0, x0 - 1), y = Math.max(0, y0 - 1);
  return { x, y, w: Math.min(size, x1 + 2) - x, h: Math.min(size, y1 + 2) - y };
}

function number(value: number) {
  return Number(value.toFixed(3)).toString();
}

function linearTreeAge(targetAge: number) {
  // Invert the app's age curve, then apply it again to keep stages uniform in displayed tree age.
  const progress = ((targetAge - MIN_AGE) / (MAX_AGE - MIN_AGE)) ** (1 / 0.75);
  return MIN_AGE + (MAX_AGE - MIN_AGE) * progress ** 0.75;
}

mkdirSync(OUT, { recursive: true });
const tree = createTree(PICKER_SEED, "cherry");
const placements: StagePlace[] = [];
let totalBytes = 0;

for (let stage = 0; stage < STAGE_COUNT; stage++) {
  const targetAge = MIN_AGE + (MAX_AGE - MIN_AGE) * stage / (STAGE_COUNT - 1);
  const final = stage === STAGE_COUNT - 1;
  const px = final ? FINAL_PX : IMAGE_PX;
  const canvas = createCanvas(px, px);
  const ctx = canvas.getContext("2d");
  const padding = px * TREE_IMAGE_PADDING;
  ctx.translate(padding, padding);
  ctx.scale((px - 2 * padding) / TREE_SIZE, (px - 2 * padding) / TREE_SIZE);
  const layout = tree.layout(linearTreeAge(targetAge), HEALTH, TREE_SIZE);
  const rig = tree.rig(layout);
  for (const layer of LAYERS) rig.paintPart(ctx as unknown as Pen, layer);

  const { x, y, w, h } = paintedBounds(ctx.getImageData(0, 0, px, px).data, px);
  const cropped = createCanvas(w, h);
  cropped.getContext("2d").drawImage(canvas, x, y, w, h, 0, 0, w, h);
  const data = cropped.encodeSync("webp", final ? 95 : 78);
  const file = `cherry-${stage}.webp`;
  writeFileSync(join(OUT, file), data);
  totalBytes += data.length;
  const scale = IMAGE_PX / px;
  placements.push({
    file,
    x: Number((x * scale).toFixed(3)),
    y: Number((y * scale).toFixed(3)),
    w: Number((w * scale).toFixed(3)),
    h: Number((h * scale).toFixed(3)),
    pw: w,
    ph: h,
  });
}

writeFileSync(MODULE, [
  "// Generated by scripts/render-hero.ts. Do not edit.",
  'import type { StagePlace } from "./stages";',
  "",
  "/** Cherry hero growth, evenly spaced from tree age 3 to 90. */",
  `export const HERO_STAGES: StagePlace[] = ${JSON.stringify(placements, null, 2)};`,
  "",
].join("\n"));

console.log(`${placements.length} images, ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
